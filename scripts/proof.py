"""Save the text output of four self-check commands under docs/proof/ (Step 54): ``python tasks.py proof``.

Each file starts with a header: the command that made it, the date, the commit hash and whether the working tree was
clean (the files this script and scripts/results.py write are not counted). The body is the command's own output,
unchanged except that a temporary folder path (which names the local user account) is replaced by
``<temporary folder>``. No screenshots. Nothing is typed by hand.

Usage (Windows):  python tasks.py proof
"""

from __future__ import annotations

import re
import subprocess
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))

from results import tree_state  # noqa: E402  (the same rule for both: the generated files are not counted)

PROOF = ROOT / "docs" / "proof"
COMMANDS = {
    "verify": ["tasks.py", "verify"],
    "readiness": ["tasks.py", "readiness"],
    "probe-protocol-version": ["tasks.py", "probe-protocol-version"],
    "inspector-replay": ["tasks.py", "inspector-replay"],
}
WINDOWS_PATH = re.compile(r"[A-Za-z]:\\[^\s|]*?\\(?=[^\\\s|]+\.sqlite3)")


def scrub(text: str) -> str:
    """Replace a Windows folder path that precedes a state-file name with a neutral label."""
    return WINDOWS_PATH.sub("<temporary folder>\\\\", text)


def header(name: str, today: str, commit: str, tree: str, exit_code: int) -> str:
    return (
        f"Generated by: python tasks.py proof (runs `python tasks.py {name}`)\n"
        f"Command: python tasks.py {name}\n"
        f"Date: {today}\n"
        f"Commit: {commit}\n"
        f"Working tree: {tree}\n"
        f"Exit code: {exit_code}\n"
        "Machine: the builder's Windows PC, mock mode, no AWS, no model call, no network call to any outside service.\n"
        + "=" * 78
        + "\n"
    )


def _git(*args: str) -> str:
    return subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True).stdout.strip()


def main() -> int:
    if len(sys.argv) > 1:
        print("proof: takes no options.", file=sys.stderr)
        return 2
    commit = _git("rev-parse", "--short", "HEAD") or "not recorded"
    status = subprocess.run(["git", "status", "--porcelain"], cwd=ROOT, capture_output=True, text=True).stdout
    tree = tree_state(status)
    PROOF.mkdir(parents=True, exist_ok=True)
    worst = 0
    for name, cmd in COMMANDS.items():
        done = subprocess.run(
            [sys.executable, "-B", *cmd], cwd=ROOT, capture_output=True, text=True, encoding="utf-8", timeout=600
        )
        body = scrub((done.stdout + done.stderr).replace("\r\n", "\n"))
        text = header(name, date.today().isoformat(), commit, tree, done.returncode) + body
        (PROOF / f"{name}.txt").write_bytes(text.encode("utf-8"))
        print(f"proof: docs/proof/{name}.txt (exit code {done.returncode})")
        worst = max(worst, done.returncode)
    return worst


if __name__ == "__main__":
    raise SystemExit(main())

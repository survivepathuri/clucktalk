"""Step 54 part A: the saved outputs under docs/proof/ (written by ``python tasks.py proof``) and docs/RESULTS.md (written
by ``python tasks.py results``) exist, say how they were made, and carry no local account name."""

from __future__ import annotations

import re
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[2]
BACKSLASH_USERS = "\\" + "Users" + "\\"


@pytest.mark.parametrize("name", ["verify", "readiness", "probe-protocol-version", "inspector-replay"])
def test_each_proof_file_has_its_header_and_no_local_account_name(name):
    text = (ROOT / "docs" / "proof" / f"{name}.txt").read_text(encoding="utf-8")
    assert text.startswith("Generated by: python tasks.py proof")
    assert f"Command: python tasks.py {name}\n" in text
    assert re.search(r"^Commit: [0-9a-f]{7,}$", text, re.M)
    assert re.search(r"^Date: 20\d\d-\d\d-\d\d$", text, re.M)
    assert BACKSLASH_USERS not in text and "ADMIN" not in text


def test_the_results_file_says_how_it_was_made_and_what_it_is_not():
    text = (ROOT / "docs" / "RESULTS.md").read_text(encoding="utf-8")
    assert "Generated by `python tasks.py results`" in text and "not an Amazon verdict" in text
    assert "server time on localhost, mock mode, not Amazon's 500 ms round trip" in text
    assert re.search(r"at commit `[0-9a-f]{7,}`", text)
    assert "[PILOT NUMBERS: to be filled on <date> from python tasks.py pilot-stats]" in text
    assert BACKSLASH_USERS not in text and "ADMIN" not in text
